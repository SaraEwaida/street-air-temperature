"""Tools the experiment agent can call. Each tool is plain Python, validated and logged.

Guardrails
- Read-only on data and code: tools read the dataset and write only under outputs/agent/.
- A budget on experiments per session; parameters are checked against allowed ranges.
- Every call (arguments, result summary, time) is logged, and the log is appended to the
  report by code, so the report always shows exactly what was run.
- Report numbers come from the logged results, not from the language model: the results
  table is generated by code and appended to the model's narrative.
"""

from __future__ import annotations

import json
import re
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from .. import model

FEATURE_GROUPS = {
    "landcover": [c for c in model.SITE if c.startswith("frac_")],
    "vegetation": ["ndvi_100m", "ndvi_500m"],
    "elevation": ["elev_minus_cell_m"],
    "time": list(model.TIME),
    "weather": list(model.WEATHER),
}
PARAM_RANGES = {   # allowed LightGBM settings: (type, min, max)
    "n_estimators": (int, 50, 1500),
    "learning_rate": (float, 0.005, 0.3),
    "num_leaves": (int, 4, 127),
    "min_child_samples": (int, 20, 20000),
    "feature_fraction": (float, 0.3, 1.0),
    "bagging_fraction": (float, 0.3, 1.0),
}


class ToolError(ValueError):
    """Returned to the agent as an error message; the agent can correct itself."""


class Toolbox:
    def __init__(self, cfg: dict[str, Any], dataset: pd.DataFrame, out_dir: str | Path,
                 max_experiments: int = 8, hour_stride: int = 3):
        self.cfg = cfg
        self.out = Path(out_dir)
        (self.out / "experiments").mkdir(parents=True, exist_ok=True)
        (self.out / "reports").mkdir(parents=True, exist_ok=True)
        self.hour_stride = hour_stride
        # Same subsample for every experiment, so runs are comparable and studies stay fast
        self.df = dataset[dataset.time.dt.hour % hour_stride == 0].reset_index(drop=True) if hour_stride > 1 else dataset
        self.full_rows = len(dataset)
        self.max_experiments = max_experiments
        self.experiments_run = 0
        self.log: list[dict[str, Any]] = []
        self.reports: list[Path] = []

    # ------------------------------------------------------------------ tool specs
    SPECS = [
        {"name": "check_data",
         "description": "Data quality checks on the station-hour table: stations, coverage, missing values per "
                        "feature, value ranges, duplicates and gaps. Run this first.",
         "input_schema": {"type": "object", "properties": {}}},
        {"name": "run_experiment",
         "description": "Leave-one-station-out evaluation of a LightGBM correction to ERA5 (each of the stations is "
                        "held out in turn). Returns MAE/RMSE/bias overall, night/day and per network, next to raw "
                        "ERA5 on the same rows. Costs one unit of the experiment budget.",
         "input_schema": {"type": "object", "properties": {
             "name": {"type": "string", "description": "Short unique id, letters, digits, '-' or '_'"},
             "params": {"type": "object", "description": "LightGBM settings to override: " +
                        ", ".join(f"{k} ({t.__name__} {lo}-{hi})" for k, (t, lo, hi) in PARAM_RANGES.items())},
             "drop_feature_groups": {"type": "array", "items": {"type": "string", "enum": list(FEATURE_GROUPS)},
                                     "description": "Feature groups to leave out (ablation)"},
             "rationale": {"type": "string", "description": "One sentence: what this run tests"}},
             "required": ["name", "rationale"]}},
        {"name": "list_experiments",
         "description": "All experiments run so far in this output folder, with headline metrics.",
         "input_schema": {"type": "object", "properties": {}}},
        {"name": "compare_experiments",
         "description": "Side-by-side metrics for the named experiments.",
         "input_schema": {"type": "object", "properties": {"names": {"type": "array", "items": {"type": "string"}}},
                          "required": ["names"]}},
        {"name": "write_report",
         "description": "Write the final markdown report: what was tested, what the results show, which "
                        "configuration to adopt and why, and caveats. A results table and the full tool log are "
                        "appended automatically, so do not paste raw tables.",
         "input_schema": {"type": "object", "properties": {"title": {"type": "string"},
                                                           "markdown": {"type": "string"}},
                          "required": ["title", "markdown"]}},
    ]

    # ------------------------------------------------------------------ dispatch
    def call(self, name: str, args: dict[str, Any]) -> tuple[str, bool]:
        """Run a tool; returns (JSON text for the model, is_error)."""
        t0 = time.time()
        fn = getattr(self, f"tool_{name}", None)
        try:
            if fn is None:
                raise ToolError(f"Unknown tool {name!r}")
            result, err = fn(**(args or {})), False
        except ToolError as e:
            result, err = {"error": str(e)}, True
        except TypeError as e:
            result, err = {"error": f"Bad arguments: {e}"}, True
        self.log.append({"tool": name, "args": args, "error": err, "seconds": round(time.time() - t0, 1),
                         "summary": _short(result)})
        return json.dumps(result, default=_json), err

    # ------------------------------------------------------------------ tools
    def tool_check_data(self) -> dict[str, Any]:
        df = model.add_time_features(self.df)      # time features are derived, as in the model
        feats = [c for g in FEATURE_GROUPS.values() for c in g if c in df]
        cov = df.groupby("station").size()
        expected = len(pd.date_range(df.time.min(), df.time.max(), freq=f"{self.hour_stride}h"))
        issues = []
        missing = {c: round(float(df[c].isna().mean()), 4) for c in feats + ["t_obs", "t_era5"] if c in df}
        for c, v in missing.items():
            if v > 0.05:
                issues.append(f"{c}: {v:.1%} missing")
        dup = int(df.duplicated(["station", "time"]).sum())
        if dup:
            issues.append(f"{dup} duplicate station-hours")
        low = cov[cov / expected < 0.55]
        if len(low):
            issues.append(f"low coverage: {', '.join(low.index)}")
        diff = (df.t_obs - df.t_era5).abs()
        if (diff > 15).any():
            issues.append(f"{int((diff > 15).sum())} rows where station and ERA5 differ by more than 15 C")
        absent = [g for g, cols in FEATURE_GROUPS.items() if not any(c in df for c in cols)]
        if absent:
            issues.append(f"feature groups with no columns: {absent}")
        return {
            "rows_used": int(len(df)), "rows_full": int(self.full_rows), "hour_stride": self.hour_stride,
            "stations": int(df.station.nunique()),
            "networks": df.network.value_counts().to_dict() if "network" in df else {},
            "coverage_min_max": [round(float(cov.min() / expected), 3), round(float(cov.max() / expected), 3)],
            "t_obs_range_c": [round(float(df.t_obs.min()), 1), round(float(df.t_obs.max()), 1)],
            "missing_share": {k: v for k, v in missing.items() if v > 0},
            "issues": issues or ["none found"],
        }

    def tool_run_experiment(self, name: str, rationale: str, params: dict | None = None,
                            drop_feature_groups: list | None = None) -> dict[str, Any]:
        if not re.fullmatch(r"[A-Za-z0-9_-]{1,40}", name or ""):
            raise ToolError("name must be 1-40 letters, digits, '-' or '_'")
        if (self.out / "experiments" / f"{name}.json").exists():
            raise ToolError(f"experiment {name!r} already exists; choose another name")
        if self.experiments_run >= self.max_experiments:
            raise ToolError(f"experiment budget of {self.max_experiments} used up; compare results and write the report")
        params = dict(params or {})
        for k, v in params.items():
            if k not in PARAM_RANGES:
                raise ToolError(f"parameter {k!r} not allowed; allowed: {list(PARAM_RANGES)}")
            typ, lo, hi = PARAM_RANGES[k]
            try:
                v = typ(v)
            except (TypeError, ValueError):
                raise ToolError(f"{k} must be {typ.__name__}") from None
            if not lo <= v <= hi:
                raise ToolError(f"{k}={v} outside allowed range {lo}-{hi}")
            params[k] = v
        drop = list(drop_feature_groups or [])
        bad = [g for g in drop if g not in FEATURE_GROUPS]
        if bad:
            raise ToolError(f"unknown feature groups {bad}; choose from {list(FEATURE_GROUPS)}")
        dropped = {c for g in drop for c in FEATURE_GROUPS[g]}
        feats = [c for c in model.feature_list(model.add_time_features(self.df)) if c not in dropped]
        if not feats:
            raise ToolError("no features left after dropping those groups")

        lgb_params = {**self.cfg["model"]["lightgbm"], **params}
        cfg = {**self.cfg, "model": {**self.cfg["model"], "lightgbm": lgb_params}}
        t0 = time.time()
        oof = model.leave_one_station_out(self.df, cfg, verbose=False, features=feats, methods=("lightgbm",))
        s = model.summarise(oof)["summary"].set_index("method")
        self.experiments_run += 1

        def row(m):
            r = s.loc[m]
            return {k: round(float(r[k]), 3) for k in ("mae_c", "rmse_c", "bias_c", "mae_night_c", "mae_day_c",
                                                       "station_bias_abs_mean_c") if k in r and pd.notna(r[k])}
        nets = {i.split("[")[1].rstrip("]"): round(float(s.loc[i, "mae_c"]), 3)
                for i in s.index if i.startswith("lightgbm [")}
        rec = {"name": name, "rationale": rationale, "params": params, "lightgbm_params": lgb_params,
               "dropped_groups": drop, "n_features": len(feats), "lightgbm": row("lightgbm"),
               "era5_raw": row("era5_raw"), "lightgbm_mae_by_network": nets,
               "rows": int(len(oof)), "hour_stride": self.hour_stride, "seconds": round(time.time() - t0, 1),
               "finished_utc": datetime.now(timezone.utc).isoformat(timespec="seconds")}
        (self.out / "experiments" / f"{name}.json").write_text(json.dumps(rec, indent=2))
        # Compact answer for the model (free tiers limit tokens); the full record is on disk
        return {"name": name, "changes": params, "dropped_groups": drop, "n_features": len(feats),
                "lightgbm": rec["lightgbm"], "era5_raw_mae_c": rec["era5_raw"]["mae_c"],
                "lightgbm_mae_by_network": nets, "budget_left": self.max_experiments - self.experiments_run}

    def _records(self) -> list[dict[str, Any]]:
        return [json.loads(p.read_text()) for p in sorted((self.out / "experiments").glob("*.json"))]

    def tool_list_experiments(self) -> dict[str, Any]:
        return {"experiments": [{"name": r["name"], "mae_c": r["lightgbm"]["mae_c"], "night": r["lightgbm"].get("mae_night_c"),
                                 "day": r["lightgbm"].get("mae_day_c"), "dropped": r["dropped_groups"],
                                 "params": r["params"]} for r in self._records()],
                "budget_left": self.max_experiments - self.experiments_run}

    def tool_compare_experiments(self, names: list) -> dict[str, Any]:
        recs = {r["name"]: r for r in self._records()}
        missing = [n for n in names if n not in recs]
        if missing:
            raise ToolError(f"unknown experiments {missing}; known: {sorted(recs)}")
        return {"table": results_table([recs[n] for n in names])}

    def tool_write_report(self, title: str, markdown: str) -> dict[str, Any]:
        slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:60] or "report"
        path = self.out / "reports" / f"{datetime.now():%Y%m%d-%H%M}-{slug}.md"
        recs = self._records()
        body = [f"# {title}", "", markdown.strip(), "", "## Results (generated from the experiment logs)", "",
                f"Leave-one-station-out, every {self.hour_stride} hours of the station table "
                f"({recs[0]['rows'] if recs else 0:,} station-hours per run). Errors in °C; bias = prediction minus station.",
                "", results_table(recs), "", "## Tool log", "",
                "| # | Tool | Arguments | Result | Seconds |", "|---:|---|---|---|---:|"]
        for i, e in enumerate(self.log, 1):
            body.append(f"| {i} | {e['tool']}{' (error)' if e['error'] else ''} | `{_cell(json.dumps(e['args']))}` | "
                        f"{_cell(e['summary'])} | {e['seconds']} |")
        path.write_text("\n".join(body) + "\n")
        self.reports.append(path)
        return {"path": str(path)}


def results_table(recs: list[dict[str, Any]]) -> str:
    if not recs:
        return "_No experiments._"
    lines = ["| Experiment | Changes | Features | MAE | RMSE | Bias | Night MAE | Day MAE | Station offset | Raw ERA5 MAE |",
             "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in sorted(recs, key=lambda r: r["lightgbm"]["mae_c"]):
        ch = ", ".join([f"{k}={v}" for k, v in r["params"].items()] + [f"no {g}" for g in r["dropped_groups"]]) or "defaults"
        L, E = r["lightgbm"], r["era5_raw"]
        lines.append(f"| {r['name']} | {ch} | {r['n_features']} | {L['mae_c']:.3f} | {L['rmse_c']:.3f} | {L['bias_c']:+.3f} | "
                     f"{L.get('mae_night_c', float('nan')):.3f} | {L.get('mae_day_c', float('nan')):.3f} | "
                     f"{L.get('station_bias_abs_mean_c', float('nan')):.3f} | {E['mae_c']:.3f} |")
    return "\n".join(lines)


def _json(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    return str(o)


def _short(result: dict[str, Any]) -> str:
    if "error" in result:
        return "error: " + result["error"]
    if "lightgbm" in result:
        return f"MAE {result['lightgbm']['mae_c']:.3f} (ERA5 {result['era5_raw_mae_c']:.3f})"
    if "issues" in result:
        return f"{result['stations']} stations; issues: {'; '.join(result['issues'])}"
    if "experiments" in result:
        return f"{len(result['experiments'])} experiments"
    if "path" in result:
        return Path(result["path"]).name
    return "ok"


def _cell(s: str, n: int = 140) -> str:
    s = s.replace("|", "/").replace("\n", " ")
    return s if len(s) <= n else s[: n - 3] + "..."
